
// ============================================================
// ONE PIPELINE STAGE
//
// Normal stage:
//
//   3 inputs --> ADD3 --> +2 bits --> REGISTER
//
// Example:
//
//   IN_COUNT = 25
//
//   25 inputs
//       |
//       +-- ADD3
//       +-- ADD3
//       +-- ...
//       +-- ADD3       8 ADD3
//       |
//       +-- leftover
//       |
//       v
//      9 outputs
//
// ------------------------------------------------------------
//
// Final stage:
//
//   IN_COUNT = 3
//
//   3 inputs --> ADD3
//                    |
//                    v
//                 Rounding
//                    |
//                    v
//                 Shift
//                    |
//                    v
//                 Saturation
//                    |
//                    v
//                   ReLU
//                    |
//                    v
//                OUT_WIDTH
//                    |
//                 REGISTER
//
// ------------------------------------------------------------
//
// Final stage:
//
//   IN_COUNT = 2
//
//   2 inputs --> ADD2
//                    |
//                    v
//                 Rounding
//                    |
//                    v
//                 Shift
//                    |
//                    v
//                 Saturation
//                    |
//                    v
//                   ReLU
//                    |
//                    v
//                OUT_WIDTH
//                    |
//                 REGISTER
//
// ============================================================

module pipeline_stage #(
    parameter IN_WIDTH      = 16,
    parameter IN_COUNT      = 9,

    parameter OUT_WIDTH     = 16,
    parameter FRAC_BITS     = 4,
    parameter ENABLE_ROUND  = 1,
    parameter ENABLE_RELU   = 1
)(
    input wire                   clk,
    input wire                   rst,
    input wire                   valid_in,

    input wire                   [IN_COUNT*IN_WIDTH-1:0] data_in,

    output reg [ (((IN_COUNT/3)+(IN_COUNT%3)) *(( ((IN_COUNT/3)+(IN_COUNT%3)) == 1) ?OUT_WIDTH :(IN_WIDTH+2) ) )-1:0 ] data_out ,

    output reg valid_out
);


    // ========================================================
    // Number of outputs produced by this stage
    // ========================================================

    localparam OUT_COUNT = (IN_COUNT == 2) ? 1 : (IN_COUNT/3) + (IN_COUNT%3);


    // ========================================================
    // Width generated by ADD3
    // ========================================================

    localparam SUM_WIDTH = IN_WIDTH + 2;


    // ========================================================
    // Final stage
    //
    // 3 inputs -> ADD3
    // 2 inputs -> ADD2
    // 1 input  -> direct
    // ========================================================

    localparam IS_FINAL_STAGE = (OUT_COUNT == 1);


    // ========================================================
    // Temporary outputs of the adders
    //
    // IMPORTANT:
    // This is WIRE because it is driven by module instances.
    // ========================================================

    wire signed [SUM_WIDTH-1:0] temp [0:OUT_COUNT-1];


    genvar g;


    // ========================================================
    // ADDER GENERATION
    // ========================================================

    generate

        // ====================================================
        // NORMAL CASE
        //
        // IN_COUNT >= 3
        //
        // Every complete group of 3 gets an ADD3.
        // ====================================================

        if (IN_COUNT >= 3) begin : GEN_ADD3_GROUPS

            for (g = 0; g < IN_COUNT/3; g = g + 1) begin : GEN_ADD3

                add3 #(.DATA_WIDTH(IN_WIDTH)) u_add3 (
                    .A(data_in[(3*g+0)*IN_WIDTH +: IN_WIDTH]),

                    .B(data_in[ (3*g+1)*IN_WIDTH +: IN_WIDTH]),

                    .C(data_in[(3*g+2)*IN_WIDTH +: IN_WIDTH ]),

                    .Y(temp[g])
                );

            end

        end

    endgenerate

    // ========================================================
    // LEFTOVER = 1
    //
    // Example:
    //
    // 10 inputs
    //
    // 3 ADD3
    // 1 leftover
    //
    // outputs = 4
    // ========================================================

    generate

        if ((IN_COUNT >= 3) && ((IN_COUNT % 3) == 1)) begin : GEN_LEFTOVER_1

         assign temp[OUT_COUNT-1] = {{2{data_in[(IN_COUNT-1)*IN_WIDTH + IN_WIDTH-1]}}, data_in[(IN_COUNT-1)*IN_WIDTH +: IN_WIDTH]};

        end

    endgenerate

    // ========================================================
    // LEFTOVER = 2
    //
    // Example:
    //
    // 11 inputs
    //
    // 3 ADD3
    // 2 leftovers
    //
    // outputs = 5
    // ========================================================

    generate

        if ((IN_COUNT >= 3) && ((IN_COUNT % 3) == 2)) begin : GEN_LEFTOVER_2

       assign temp[OUT_COUNT-2] = {{2{data_in[(IN_COUNT-2)*IN_WIDTH + IN_WIDTH-1]}},  data_in[(IN_COUNT-2)*IN_WIDTH +: IN_WIDTH]};

       assign temp[OUT_COUNT-1] = {{2{data_in[(IN_COUNT-1)*IN_WIDTH + IN_WIDTH-1]}},  data_in[(IN_COUNT-1)*IN_WIDTH +: IN_WIDTH]};
        end

    endgenerate



    // ========================================================
    // FINAL ADDER
    //
    // IN_COUNT = 2
    //
    // Use ADD2 instead of ADD3.
    // ========================================================

    generate

        if (IN_COUNT == 2) begin : GEN_FINAL_ADD2

            add2 #( .DATA_WIDTH(IN_WIDTH) ) u_add2 (

                .A($signed(data_in[  0*IN_WIDTH  +: IN_WIDTH  ])),

                .B( $signed(data_in[ 1*IN_WIDTH +: IN_WIDTH  ])),

                .Y(temp[0]) );

        end

    endgenerate



    // ========================================================
    // FINAL STAGE
    //
    // IN_COUNT = 2
    //
    // ADD2 -> processing -> 16 bit
    //
    // IN_COUNT = 1
    //
    // direct -> processing -> 16 bit
    // ========================================================

    generate

        if (IS_FINAL_STAGE) begin : GEN_FINAL_STAGE

            reg signed [SUM_WIDTH-1:0] sum_value;
            reg signed [SUM_WIDTH-1:0] rounding_offset;
            reg signed [SUM_WIDTH+1:0] scaled_value;
            reg signed [SUM_WIDTH-1:0] truncated_value;
            reg signed [OUT_WIDTH-1:0] processed_value;

            // =================================================
            // MIDPOINT PIPELINE REGISTERS
            // =================================================
            reg signed [SUM_WIDTH-1:0] sum_value_reg;
            reg                        valid_sum_reg;

            localparam signed [OUT_WIDTH-1:0] MAX_VALUE = {1'b0, {(OUT_WIDTH-1){1'b1}}};
            localparam signed [OUT_WIDTH-1:0] MIN_VALUE = {1'b1, {(OUT_WIDTH-1){1'b0}}};

            // =================================================
            // 1. COMBINATIONAL SUM EXTRACTION
            // =================================================
            always @(*) begin
                if (IN_COUNT == 1) begin
                   sum_value = {{2{data_in[IN_WIDTH-1]}}, data_in[0 +: IN_WIDTH]};
                end
                else begin
                   sum_value = $signed(temp[0]);
                end
            end

            // =================================================
            // 2. MIDPOINT PIPELINE
            // =================================================
            always @(posedge clk) begin
                if (!rst) begin
                    sum_value_reg <= {SUM_WIDTH{1'b0}};
                    valid_sum_reg <= 1'b0;
                end
                else begin
                    valid_sum_reg <= valid_in;
                    if (valid_in)
                    begin
                       sum_value_reg <= sum_value; 
                    end
                end
            end

            // =================================================
            // 3. FORMATTING LOGIC (Reads from Registered Sum)
            // =================================================
            always @(*) begin
                rounding_offset = {SUM_WIDTH{1'b0}};
                if (ENABLE_ROUND && (FRAC_BITS > 0)) begin
                    rounding_offset = ({{(SUM_WIDTH-1){1'b0}}, 1'b1} << (FRAC_BITS - 1));
                end

                scaled_value = sum_value_reg + rounding_offset; 

                if (FRAC_BITS > 0)
                    truncated_value = scaled_value >>> FRAC_BITS;
                else
                    truncated_value = scaled_value;

                if (truncated_value > MAX_VALUE)
                    processed_value = MAX_VALUE;
                else if (truncated_value < MIN_VALUE)
                    processed_value = MIN_VALUE;
                else
                    processed_value = truncated_value[OUT_WIDTH-1:0];

                if (ENABLE_RELU) begin
                    if (processed_value[OUT_WIDTH-1])
                        processed_value =  {OUT_WIDTH{1'b0}} ;
                end
            end

            // =================================================
            // 4. FINAL OUTPUT REGISTER
            // =================================================
            always @(posedge clk) begin
                if (!rst) begin
                    valid_out <= 1'b0;
                    data_out  <= {OUT_WIDTH{1'b0}};
                end
                else begin
                    valid_out <= valid_sum_reg;
                    if (valid_sum_reg) begin
                        data_out  <= processed_value;
                    end
                end
            end

        end


        // ====================================================
        // NORMAL PIPELINE STAGE
        //
        // IN_COUNT > 2
        //
        // ADD3 instances -> REGISTER
        // ====================================================

        else begin : GEN_NORMAL_STAGE

            integer j;

            always @(posedge clk) begin

                if (!rst) begin

                    valid_out <= 1'b0;

                    data_out <= { OUT_COUNT*SUM_WIDTH{1'b0} };

                end

                else begin

                    valid_out <= valid_in;
                    if (valid_in) 
                    begin
                        for (j = 0; j < OUT_COUNT; j = j + 1) begin
                            data_out[ j*SUM_WIDTH +: SUM_WIDTH ] <= temp[j];
                        end
                    end
                end

            end

        end

    endgenerate

endmodule